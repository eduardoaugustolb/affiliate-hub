import { beforeEach, describe, expect, it, mock } from "bun:test";
import { IdGeneratorFake } from "@test/support/fakes/IdGeneratorFake";
import { ProductCodeGeneratorFake } from "@test/support/fakes/ProductCodeGeneratorFake";
import { ProductRepositoryFake } from "@test/support/fakes/ProductRepositoryFake";
import { productFake } from "@test/support/fixtures/product";
import { ApplicationError } from "@/application/errors/ApplicationError";
import { ProductCodeAlreadyExistsError } from "@/application/errors/ProductCodeAlreadyExistsError";
import type { IdGenerator } from "@/application/IdGenerator";
import type { ProductCodeGenerator } from "@/application/ProductCodeGenerator";
import type { ProductRepository } from "@/application/repositories/ProductRepository";
import { CreateProduct } from "@/application/usecases/commands/CreateProduct";
import { DomainError } from "@/domain/errors/DomainError";

describe("CreateProduct usecase", () => {
	let repo: ProductRepository;
	let idGenerator: IdGenerator;
	let productCodeGenerator: ProductCodeGenerator;
	let useCase: CreateProduct;

	const input = {
		destinationUrl: productFake.destinationUrl,
		marketplace: productFake.marketplace,
		imageUrl: productFake.imageUrl,
		status: productFake.status,
	};

	beforeEach(() => {
		idGenerator = new IdGeneratorFake();
		repo = new ProductRepositoryFake(idGenerator);
		productCodeGenerator = new ProductCodeGeneratorFake();

		useCase = new CreateProduct(repo, productCodeGenerator);
	});

	it("should persist a product successfully", async () => {
		const result = await useCase.execute(undefined, input);

		expect(result).toBeUndefined();
	});

	it("should generate an id when creating a product", async () => {
		const generate = mock(() => "product-id");

		idGenerator.generate = generate;

		await useCase.execute(undefined, input);

		expect(generate).toHaveBeenCalledTimes(1);
	});

	it("should generate a product code when creating a product", async () => {
		const generate = mock(() => "ABC123");

		productCodeGenerator.generate = generate;

		await useCase.execute(undefined, input);

		expect(generate).toHaveBeenCalledTimes(1);
	});

	it("should persist the product generated by the usecase", async () => {
		const save = mock(repo.save.bind(repo));

		repo.save = save;

		await useCase.execute(undefined, input);

		expect(save).toHaveBeenCalledTimes(1);

		const call = save.mock.calls.at(0);

		expect(call).toBeDefined();

		if (!call) {
			throw new Error("Expected repository save to be called");
		}

		const product = call[0];

		expect(product.getDestinationUrl()).toBe(input.destinationUrl);
		expect(product.getMarketplace()).toBe(input.marketplace);
		expect(product.getImageUrl()).toBe(input.imageUrl);
		expect(product.getStatus()).toBe(input.status);
	});

	it("should retry with a new code when the generated code already exists", async () => {
		const generate = mock()
			.mockReturnValueOnce("ABC123")
			.mockReturnValueOnce("DEF456");

		productCodeGenerator.generate = generate;

		let attempts = 0;

		const save = mock(async () => {
			attempts++;

			if (attempts === 1) {
				throw new ProductCodeAlreadyExistsError();
			}
		});

		repo.save = save;

		const result = await useCase.execute(undefined, input);

		expect(result).toBeUndefined();
		expect(generate).toHaveBeenCalledTimes(2);
		expect(save).toHaveBeenCalledTimes(2);
	});

	it("should persist the product using the new code after a collision", async () => {
		productCodeGenerator.generate = mock()
			.mockReturnValueOnce("ABC123")
			.mockReturnValueOnce("DEF456");

		const savedCodes: string[] = [];

		repo.save = mock(async (product) => {
			savedCodes.push(product.code.getValue());

			if (savedCodes.length === 1) {
				throw new ProductCodeAlreadyExistsError();
			}
		});

		await useCase.execute(undefined, input);

		expect(savedCodes).toEqual(["ABC123", "DEF456"]);
	});

	it("should throw an ApplicationError after reaching the maximum number of retries", async () => {
		productCodeGenerator.generate = mock(() => "ABC123");

		const save = mock(async () => {
			throw new ProductCodeAlreadyExistsError();
		});

		repo.save = save;

		try {
			await useCase.execute(undefined, input);

			throw new Error("Expected use case to throw");
		} catch (error) {
			expect(error).toEqual(
				new ApplicationError("Failed to generate unique code"),
			);
		}

		expect(productCodeGenerator.generate).toHaveBeenCalledTimes(10);
		expect(save).toHaveBeenCalledTimes(10);
	});

	it("should not retry when repository throws an unrelated error", async () => {
		const repositoryError = new Error("Database unavailable");

		productCodeGenerator.generate = mock(() => "ABC123");

		const save = mock(async () => {
			throw repositoryError;
		});

		repo.save = save;

		try {
			await useCase.execute(undefined, input);

			throw new Error("Expected use case to throw");
		} catch (error) {
			expect(error).toBe(repositoryError);
		}

		expect(productCodeGenerator.generate).toHaveBeenCalledTimes(1);
		expect(save).toHaveBeenCalledTimes(1);
	});

	it.each(["", "http://example.com", "example.com", "https://"])(
		"should throw an error when trying to persist a product with invalid destinationUrl",
		async (destinationUrl) => {
			try {
				await useCase.execute(undefined, {
					...input,
					destinationUrl,
				});

				throw new Error("Expected use case to throw");
			} catch (error) {
				expect(error).toEqual(
					new DomainError("Invalid product destination URL"),
				);
			}
		},
	);

	it.each(["", "http://example.com", "example.com", "https://"])(
		"should throw an error when trying to persist a product with invalid imageUrl",
		async (imageUrl) => {
			try {
				await useCase.execute(undefined, {
					...input,
					imageUrl,
				});

				throw new Error("Expected use case to throw");
			} catch (error) {
				expect(error).toEqual(new DomainError("Invalid product image URL"));
			}
		},
	);

	it.each(["", "invalid", "example"])(
		"should throw an error when trying to persist a product with invalid status",
		async (status) => {
			try {
				await useCase.execute(undefined, {
					...input,
					status,
				});

				throw new Error("Expected use case to throw");
			} catch (error) {
				expect(error).toEqual(new DomainError("Invalid product status"));
			}
		},
	);

	it.each(["", "invalid", "example", "amazon ;)"])(
		"should throw an error when trying to persist a product with invalid marketplace",
		async (marketplace) => {
			try {
				await useCase.execute(undefined, {
					...input,
					marketplace,
				});

				throw new Error("Expected use case to throw");
			} catch (error) {
				expect(error).toEqual(new DomainError("Invalid product marketplace"));
			}
		},
	);

	it("should not persist a product when domain validation fails", async () => {
		const save = mock(repo.save.bind(repo));

		repo.save = save;

		try {
			await useCase.execute(undefined, {
				...input,
				destinationUrl: "invalid",
			});

			throw new Error("Expected use case to throw");
		} catch (error) {
			expect(error).toBeInstanceOf(DomainError);
		}

		expect(save).not.toHaveBeenCalled();
	});
});
